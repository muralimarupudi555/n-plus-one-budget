"""Run the tool for real and commit what it printed.

A README that quotes invented output is a README that drifts. This runs the real command
and writes what came back, exit codes included, so the block in
the documentation is a transcript rather than a description.

Regenerated by `make bench` rather than by `make verify`. The query counts in it are exact
and would be safe in the gate, but the transcript also carries wall times, and a gate that
leaves uncommitted changes behind every time it runs is a gate people stop reading the
output of.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "cli-output.md"

INVOCATIONS = [
    ("A page that loads its children one at a time",
     ["--strategy", "n_plus_one", "--parents", "100"]),
    ("The same page, batched",
     ["--strategy", "batched", "--parents", "100"]),
    ("The same page as a join, which the counter approves of",
     ["--strategy", "join", "--parents", "100", "--bio-width", "2000"]),
    ("A scenario that cannot show the effect",
     ["--children-each", "0"]),
]

PREAMBLE = (
    "Generated by `tools/capture_cli.py`, which runs the real command against a real "
    "page load against a real PostgreSQL and records what came back. Regenerated by "
    "`make bench`; the query counts are exact and only the timings move."
)


def main() -> None:
    sections = ["# Captured output", "", PREAMBLE, ""]
    for title, args in INVOCATIONS:
        result = subprocess.run(
            ["n-plus-one-budget", *args],
            cwd=ROOT, capture_output=True, text=True, check=False,
        )
        body = (result.stdout + result.stderr).rstrip()
        sections += [
            f"## {title}", "",
            "```console",
            f"$ n-plus-one-budget {' '.join(args)}",
            body,
            "$ echo $?", str(result.returncode),
            "```", "",
        ]
        print(f"  captured `{' '.join(args)}` -> exit {result.returncode}")

    OUT.write_text("\n".join(sections))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
